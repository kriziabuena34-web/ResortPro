/// Mga wikang pwedeng piliin sa admin panel.
/// Para magdagdag ng bagong wika: idagdag dito, tapos lagyan ng
/// translations sa `_strings`, `_monthNames`, `_monthShort` at `_weekdays`.
enum AppLanguage {
  en('English', 'EN'),
  fil('Filipino', 'FIL'),
  ceb('Cebuano (Bisaya)', 'CEB');

  const AppLanguage(this.nativeName, this.shortCode);
  final String nativeName;
  final String shortCode;
}

/// Kasalukuyang wika. Nire-rebuild ang screens kapag nagbago ito.
final ValueNotifier<AppLanguage> appLanguage = ValueNotifier(AppLanguage.en);

const _prefsKey = 'admin_language';

/// Tawagin sa main() bago mag-runApp para ma-load ang huling napiling wika.
Future<void> loadSavedLanguage() async {
  try {
    final prefs = await SharedPreferences.getInstance();
    final saved = prefs.getString(_prefsKey);
    appLanguage.value = AppLanguage.values.firstWhere(
      (l) => l.name == saved,
      orElse: () => AppLanguage.en,
    );
  } catch (_) {
    // Kapag hindi mabasa ang saved setting, English ang default.
  }
}

Future<void> setLanguage(AppLanguage language) async {
  appLanguage.value = language;
  try {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_prefsKey, language.name);
  } catch (_) {}
}

/// Kunin ang text sa kasalukuyang wika. Pwedeng may placeholders, hal.
/// `tr('paxCount', {'n': 5})` para sa "{n} pax".
String tr(String key, [Map<String, Object?> args = const {}]) {
  var text = _strings[appLanguage.value]?[key] ?? _strings[AppLanguage.en]![key] ?? key;
  args.forEach((name, value) {
    text = text.replaceAll('{$name}', '$value');
  });
  return text;
}

